export const USAGE = `tt-testops — выгрузка и проверка тест-кейсов Allure TestOps

Команды:
  case <id>       Один кейс по ID → Markdown (или --format json). Когда работаешь над конкретным кейсом.
  list <запрос>   Все кейсы по запросу → Markdown каждого + сводка проблемных. Когда нужен раздел/пачка.
  audit <запрос>  Только список проблем по запросу (старый формат, пустой сценарий…).
  count <запрос>  Сколько кейсов подходит под запрос — одно число, без выгрузки самих кейсов.
  fields [имя]    Без имени — обзор проекта: поля с числом значений и слои с числом кейсов.
                  С именем поля (или layer) — его значения и сколько кейсов на каждом.
                  --find <текст> — где в проекте встречается это слово, готовыми условиями запроса.
  link <запрос>   Ссылка на фильтр TestOps по запросу — открыть в браузере или переслать коллеге.
  attachments <id>  Положить вложения кейса файлами и напечатать пути. --out <каталог> — куда
                  именно; без него — в хранилище профиля. Команда case кладёт их сама.
  projects        Согласованный список проектов из конфигурации и что есть на сервере сверх него.
  trees           Деревья разделов проекта: из каких полей собраны и какое сейчас рабочее.
  cache [clear]   Что лежит в локальном хранилище; с аргументом clear — очистить.
  config          Настройки: без подкоманды — просмотр; init — создать раскладку;
                  use <профиль> — переключить профиль; profiles — список профилей.
  setup [путь]    Как поставить инструмент именно в этот проект. Ничего не меняет — объясняет.
  init [путь]       Разложить скилл, чтобы агент знал про инструмент. Спросит, куда именно;
                    до ответа не создаёт ни одного файла. По умолчанию — текущий проект.
                    --for claude,agents — ответить заранее, без вопроса.
  update             Обновить пакет до последней опубликованной версии через npm.
  --version       Версия установленного пакета.

<запрос> — это AQL либо ссылка на фильтр TestOps (адрес из адресной строки, целиком в кавычках).

Опции:
  --profile <профиль>     выбор профиля настроек (см. tt-testops config)
  --config <путь>         путь к profile.json вместо выбора по профилю
  --project <id|имя>      проект (имена — из поля projects в profile.json); перекрывает проект из ссылки.
                          Повторяется: несколько проектов в одном документе (см. ниже)
  --limit N               максимум кейсов в list/audit НА КАЖДЫЙ проект: два проекта
                          с --limit 3 дадут до 6 кейсов
  --format markdown|json|html|raw
                          формат вывода (по умолчанию markdown; html — только case и list;
                          raw — сырой ответ TestOps как есть, только для case)
  --out <файл>            записать в файл вместо экрана
  --no-marks              не печатать пометки (баннер старого формата, сводку по пачке).
                          По умолчанию пометки включены. На команду audit не влияет: она и есть
                          отчёт о пометках. Данные кейса не меняются ни при каком значении.
  --refresh               перечитать всё заново, не используя локальное хранилище
  --tree <название|none>  рабочее дерево разделов для этого вызова — названием, как в интерфейсе
                          TestOps (идентификатор тоже принимается; см. команду trees); none — путь
                          не нужен. Деревьев у проекта несколько, а выбора нет — case и list
                          останавливаются до выгрузки и перечисляют деревья.
                          Постоянный выбор — поле trees в profile.json: {"<проект>": <дерево>}
                          или {"<проект>": "none"}, если путь не нужен
  --find <текст>          только для fields: искать текст в значениях полей и в слоях проекта
  --rql <запрос>          запрос явным флагом; --rql-file <файл> — запрос из файла.
                          Оба повторяются наравне с --project

Несколько проектов в одном вызове (list, audit и count):
  Запрос относится к ближайшему --project слева от него. Один запрос на несколько
  проектов выполняется в каждом. Проектов и запросов поровну — пара к паре; иначе отказ.
  Кейсы идут в порядке проектов, повторный вызов даёт тот же файл побайтово.

  tt-testops list --project <ид-2> --rql 'cf["<Поле-2>"] = "Раздел Б"' \\
                  --project <ид>  --rql 'cf["<Поле-1>"] = "Раздел А"' --format html
  tt-testops list 'tag = "<тег>"' --project <ид-1> --project <ид-2>

Запрос только по идентификаторам проектом не ограничен:
  tt-testops list 'id in [<ид-1>, <ид-2>]'   # кейсы берутся из своих проектов
  Ненайденные названы в потоке ошибок; --project не применяется, --limit режет список
  первыми идентификаторами. Любое добавочное условие возвращает запрос в границы
  проекта: искать по полям без проекта TestOps не умеет.

AQL: кастомные поля только как cf["Имя"]; операторы =  !=  ~= (содержит)  in [...]  not  is null;
     признак автоматизации — automation = true|false. Ошибся в синтаксисе — инструмент подскажет.

Настройки — ~/.tt-testops/profiles/<профиль>/profile.json и credentials.json (см. README и tt-testops config):
  TT_TESTOPS_SERVER_TESTOPS_BASE_URL — адрес сервера
  TT_TESTOPS_SERVER_TESTOPS_TOKEN — API-токен (секрет, хранится в credentials.json)
  TT_TESTOPS_DEFAULT_PROJECT — проект по умолчанию
  TT_TESTOPS_TIMEOUT_SEC — ожидание ответа TestOps в секундах (по умолчанию 30)
  TT_TESTOPS_MAX_CASES — верхний предел кейсов на проект за вызов (по умолчанию 100)
  TT_TESTOPS_CONCURRENCY — одновременные обращения к TestOps (по умолчанию 8)
  TT_TESTOPS_RETRIES — повторы при временном отказе TestOps (по умолчанию 3)
  TT_TESTOPS_FORMAT_FILE — путь к JSON со своим форматом вывода (см. README)
  TT_TESTOPS_PROFILE — имя выбранного профиля настроек

Примеры:
  tt-testops case <ид-кейса>
  tt-testops list 'tag = "<тег>"' --project <имя> --limit 20
  tt-testops list 'https://testops/project/<ид>/test-cases?search=W3si...' --limit 3
  tt-testops fields --project <ид>
  tt-testops fields <Поле> --project <ид>
  tt-testops fields --find раздел --project <ид>
  tt-testops count 'layer = "E2E"' --project <ид>
  tt-testops link 'cf["<Поле>"] = "Раздел А"' --project <ид>`;
